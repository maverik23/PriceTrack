  inicio('Inicio', SectionColors(Color(0xFFE19B1B), Color(0xFFFDEFCB), Color(0xFF7C4607)),
      SectionColors(Color(0xFFF7B83D), Color(0xFF3E2D10), Color(0xFFFAD280))),
